package excercise_while_loop;

public class Lab032_while_loop {
    public static void main(String[] args) {
        int i=0;//initialization

        while(i<10){//condition
            System.out.println(i);
            i++;//inc
        }
        for (int j = 0; j <10 ; j++) {
            System.out.println(j);
        }
    }
}
