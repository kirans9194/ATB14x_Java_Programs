package excercise_for_loop;

public class Lab028_ForLoop_greater_equal {
    public static void main(String[] args) {

        for (int i = 0; i <=10 ; i++) {
            System.out.println(i);//print 0 to 10
        }
        for (int i = 0; i <10 ; i++) {
            System.out.println(i);//print 0 to 9
        }
        for (int i = 1; i <=10 ; i++) {
            System.out.println(i);//print 1 to 10
        }
    }
}
